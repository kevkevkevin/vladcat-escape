const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const origin = 'http://127.0.0.1:3000';
const results = { checks: [], browserErrors: [] };
const check = name => { results.checks.push(name); console.log(JSON.stringify({ passed: name })); };
(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const traffic = [];
    page.on('request', r => traffic.push(r.url()));
    page.on('pageerror', e => results.browserErrors.push(e.message));
    await page.goto(origin);
    const strip = page.locator('.landing-marquee');
    const bounds = await strip.boundingBox();
    assert.ok(Math.abs(bounds.x) <= 1); assert.ok(Math.abs(bounds.width - 1440) <= 1);
    const track = page.locator('.marquee-track');
    const initial = await track.evaluate(el => getComputedStyle(el).transform);
    await page.waitForTimeout(250);
    assert.notEqual(await track.evaluate(el => getComputedStyle(el).transform), initial);
    await page.getByRole('button', { name: 'Pause marquee', exact: true }).click();
    assert.equal(await track.evaluate(el => getComputedStyle(el).animationPlayState), 'paused');
    await page.getByRole('button', { name: 'Resume marquee', exact: true }).click();
    await page.mouse.move(0, 0);
    await page.locator('.landing-hero h1').click();
    await strip.scrollIntoViewIfNeeded();
    await page.screenshot({ path: 'artifacts/marquee-desktop.png' });
    check('Marquee spans 100vw, scrolls and supports explicit pause/resume');
    await page.getByRole('button', { name: 'Open VLADCAT guide', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Your catguy guide.' });
    await dialog.waitFor();
    await dialog.getByRole('button', { name: 'Timers & leaderboard', exact: true }).click();
    await page.getByText(/The victory screen completes the run after 49 timed stages\./).waitFor();
    await page.getByLabel('Ask VLADCAT a game question').fill('end my challenge');
    await page.getByRole('button', { name: 'Send guide question' }).click();
    await page.getByText(/That run cannot be resumed afterward\./).waitFor();
    await page.screenshot({ path: 'artifacts/vladcat-guide-desktop.png' });
    const before = traffic.length;
    await page.getByLabel('Ask VLADCAT a game question').fill('How do I play?');
    await page.getByRole('button', { name: 'Send guide question' }).click();
    await page.getByText(/Quick paws, cat wrangler!/).waitFor();
    assert.equal(traffic.slice(before).filter(url => url.includes('/api/guide') || url.includes('api.openai.com')).length, 0);
    await page.getByLabel('Ask VLADCAT a game question').press('Escape');
    await dialog.waitFor({ state: 'hidden' });
    assert.equal(await page.getByRole('button', { name: 'Open VLADCAT guide', exact: true }).evaluate(el => el === document.activeElement), true);
    check('Chibi guide opens, answers local game help and returns keyboard focus on Escape');
    await page.setViewportSize({ width: 390, height: 844 });
    const mobileBounds = await strip.boundingBox();
    assert.ok(Math.abs(mobileBounds.x) <= 1); assert.ok(Math.abs(mobileBounds.width - 390) <= 1);
    await page.getByRole('button', { name: 'Open VLADCAT guide', exact: true }).click();
    const panel = await dialog.boundingBox();
    assert.ok(panel.x >= 0 && panel.y >= 0 && panel.x + panel.width <= 390 && panel.y + panel.height < 844);
    await page.screenshot({ path: 'artifacts/vladcat-guide-mobile.png' });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.getByRole('button', { name: 'Close VLADCAT guide' }).click();
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await track.evaluate(el => getComputedStyle(el).animationName), 'none');
    check('Mobile guide fits the screen, marquee has no horizontal overflow and respects reduced motion');
    await page.goto(origin+'/play');
    await page.getByRole('button', { name: 'Open VLADCAT guide', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Open VLADCAT guide', exact: true }).click();
    await dialog.getByRole('link', { name: 'Leaderboard →', exact: true }).click();
    await page.waitForURL('**/leaderboard');
    assert.equal(await dialog.count(), 0);
    assert.equal(results.browserErrors.length, 0);
    check('Guide persists across pages, its navigation works and no browser errors occur');
    const response = await page.request.post(origin+'/api/guide', { headers: { Origin: origin }, data: { message: 'How do I play?' } });
    assert.equal(response.status(), 200); assert.equal((await response.json()).mode, 'builtin');
    const invalid = await page.request.post(origin+'/api/guide', { headers: { Origin: 'https://evil.example' }, data: { message: '?' } });
    assert.equal(invalid.status(), 403);
    const oversized = await page.request.post(origin+'/api/guide', { headers: { Origin: origin }, data: { message: 'x'.repeat(401) } });
    assert.equal(oversized.status(), 400);
    check('Actual guide API provides guest help and rejects cross-origin or oversized questions');
    // Simulate live UI without any provider call or API key.
    let failure = false;
    await page.route('**/api/guide', async route => {
      if(route.request().method() === 'GET') return route.fulfill({ json: { mode: 'ai' } });
      const payload = route.request().postDataJSON();
      assert.ok(payload.history.length <= 2); assert.ok(payload.history.every(m => ['user','assistant'].includes(m.role) && m.content.length <= 240));
      await page.waitForTimeout(200);
      return failure ? route.fulfill({ status: 503, json: { error: 'Live AI is unavailable.' } }) : route.fulfill({ json: { mode: 'ai', reply: 'Mock live reply: use ↑ to jump.' } });
    });
    await page.getByRole('button', { name: 'Open VLADCAT guide', exact: true }).click();
    await page.getByText('Live AI · messages sent to OpenAI', { exact: true }).waitFor();
    await page.getByLabel('Ask VLADCAT a game question').fill('How do I jump?');
    await page.getByRole('button', { name: 'Send guide question' }).click();
    await page.getByText('Mock live reply: use ↑ to jump.', { exact: true }).waitFor();
    failure = true;
    await page.getByLabel('Ask VLADCAT a game question').fill('How do I play?');
    await page.getByRole('button', { name: 'Send guide question' }).click();
    await page.getByText('Live AI is unavailable. Showing built-in help.', { exact: true }).waitFor();
    assert.equal(results.browserErrors.length, 0);
    check('Mock live chat displays the transfer notice, sends bounded history and recovers to local help');
  } finally { await browser.close(); await fs.writeFile('artifacts/marquee-guide-results.json', JSON.stringify(results, null, 2)+'\n'); }
})().catch(e => { console.error(e.message); process.exitCode = 1; });
